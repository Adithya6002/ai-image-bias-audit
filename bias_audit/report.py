## 5. E5: Do the three models differ in perceived race? (Holm over {len(e5)})

{_fmt(e5, ["subject", "table (rows=models)", "chi2", "p", "p_holm", "cramers_v", "V 95% CI", "parity_gap_white_share", "gap 95% CI", "H0 (no bias)"])}

